"""
Table definitions: the JSON structure an Archivable declares in ``get_archive_definitions`` and a data manager turns
into SQLAlchemy tables.

A definition is ``{"name": table, "columns": [...], "inherits": parent table, "indices": [...], "constraints": [...]}``.
A column is ``{"name", "type", "type_args", "enumeration", "foreign_key", "identity", "kwargs"}``: `type` is the name
of a SQLAlchemy type (Integer, String, DateTime, Uuid, Interval, ...), `type_args` its positional arguments,
`enumeration` the name of a registered enumeration (stored by member name), `foreign_key` a "table.column" reference,
`identity` an identity clause on integer columns, and `kwargs` the Column keyword arguments (primary_key, nullable,
...). An index is ``{"name", "columns", "unique"}``; the one table constraint is
``{"foreign_key": {"columns": [...], "references": ["table.column", ...]}, "name"}``.
"""
import json
from collections.abc import Mapping, Sequence

from sqlalchemy import Column, Enum, ForeignKey, ForeignKeyConstraint, Identity, Index, MetaData, Table, types

from archivable.enumerations import EnumerationRegistry

INTEGER_TYPES = ('Integer', 'BigInteger', 'SmallInteger')


def parse_column_definition(column_def: Mapping, enumerations: EnumerationRegistry) -> Column:
    args = [column_def['name']]
    kwargs = column_def.get('kwargs', {})

    col_type_name: str | None = column_def.get('type')
    if col_type_name:
        col_type_class = getattr(types, col_type_name, None)
        if col_type_class is None:
            raise ValueError(f'Unknown column type {col_type_name!r} in definition of column {column_def["name"]!r}.')
        col_type_args = column_def.get('type_args')
        if col_type_class is types.DateTime:
            args.append(types.DateTime(timezone=True))  # archive datetimes are always aware; stored as UTC
        else:
            args.append(col_type_class(*col_type_args) if col_type_args else col_type_class)

    enumeration = column_def.get('enumeration')
    if enumeration:
        if enumeration not in enumerations:
            raise ValueError(f'Unknown enumeration {enumeration!r} in definition of column {column_def["name"]!r}; the '
                             f'registered enumerations are {enumerations.names()}. Register it with the data manager '
                             f'(register_enumerations) before the tables that use it.')
        enum_class = enumerations.get(enumeration)
        args.append(Enum(enum_class, create_type=True))

    foreign_key = column_def.get('foreign_key')
    if foreign_key:
        args.append(ForeignKey(foreign_key))

    # An SQL identity clause is only valid on integer columns (PostgreSQL rejects it elsewhere). UUID primary keys are
    # generated by Archivable (uuid7), so the flag is ignored for them.
    if column_def.get('identity') and col_type_name in INTEGER_TYPES:
        args.append(Identity())

    return Column(*args, **kwargs)


def parse_index_definition(index_def: Mapping) -> Index:
    return Index(index_def['name'], *index_def['columns'], unique=index_def.get('unique', False))


def parse_constraint_definition(constraint_def: Mapping) -> ForeignKeyConstraint:
    """Table-level constraints. Currently: {"foreign_key": {"columns": [...], "references": ["table.col", ...]}}."""
    if 'foreign_key' in constraint_def:
        fk = constraint_def['foreign_key']
        return ForeignKeyConstraint(fk['columns'], fk['references'], name=constraint_def.get('name'))
    raise ValueError(f'Unsupported table constraint definition: {constraint_def}')


def parse_table_definition(definition: Mapping, metadata: MetaData, enumerations: EnumerationRegistry) -> Table:
    kwargs = definition.get('kwargs', {})
    columns = [parse_column_definition(c, enumerations) for c in definition['columns']]
    indices = [parse_index_definition(i) for i in definition.get('indices', [])]
    constraints = [parse_constraint_definition(c) for c in definition.get('constraints', [])]
    return Table(definition['name'], metadata, *columns, *indices, *constraints, **kwargs)


def definition_differences(existing: Mapping, proposed: Mapping) -> list[str]:
    """Human-readable differences between two table definitions of the same name; empty when they agree. Column order
    is not part of a definition (columns are compared by name); everything else is."""
    differences = []

    def by_name(definition):
        return {column['name']: column for column in definition.get('columns', [])}

    existing_columns, proposed_columns = by_name(existing), by_name(proposed)
    for name in sorted(set(existing_columns) - set(proposed_columns)):
        differences.append(f'column {name!r} is missing from the new definition')
    for name in sorted(set(proposed_columns) - set(existing_columns)):
        differences.append(f'column {name!r} is new')
    for name in sorted(set(existing_columns) & set(proposed_columns)):
        if existing_columns[name] != proposed_columns[name]:
            differences.append(f'column {name!r} differs: {existing_columns[name]} versus {proposed_columns[name]}')
    for field in sorted((set(existing) | set(proposed)) - {'columns', 'name'}):
        if existing.get(field) != proposed.get(field):
            differences.append(f'{field!r} differs: {existing.get(field)!r} versus {proposed.get(field)!r}')
    return differences


def canonical_definitions_json(definitions: Sequence[Mapping], enumerations: Sequence[Mapping] = ()) -> str:
    """
    The definitions (and enumeration definitions) as one JSON document in which nothing depends on order: tables sorted
    by name, columns sorted by name, enumerations sorted by name, keys sorted. Column order is not part of a table
    definition (definition_differences); member order is part of an enumeration and is kept.
    """
    canonical_tables = []
    for definition in sorted(definitions, key=lambda d: d['name']):
        definition = dict(definition)
        definition['columns'] = sorted(definition.get('columns', []), key=lambda c: c['name'])
        canonical_tables.append(definition)
    document = {'tables': canonical_tables,
                'enumerations': sorted((dict(e) for e in enumerations), key=lambda e: e['name'])}
    return json.dumps(document, sort_keys=True, separators=(',', ':'))
